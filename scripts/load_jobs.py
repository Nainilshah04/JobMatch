"""Load and clean job postings from CSV into PostgreSQL database.

Supports loading external datasets (e.g. Kaggle) or synthetic datasets
generated by scripts/generate_jobs.py.
"""

import argparse
import csv
import logging
import os
import sys
from typing import List, Tuple, Any

# Ensure project root is in sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import psycopg2
from psycopg2.extras import execute_values
from app.config import get_settings
from app.db import init_db, get_db_connection

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)


def clean_job_row(row: dict) -> Tuple[Any, ...]:
    """Clean and cast raw CSV row values into database-ready types.
    
    Returns a tuple ordered as:
    (title, company, location, description, skills, salary, remote)
    """
    title = row.get("title", "").strip()
    company = row.get("company", "").strip()
    location = row.get("location", "").strip()
    description = row.get("description", "").strip()
    skills = row.get("skills", "").strip()
    
    # Handle optional salary
    raw_salary = row.get("salary", "").strip()
    salary = raw_salary if raw_salary else None
    
    # Cast remote to boolean
    raw_remote = str(row.get("remote", "")).strip().lower()
    remote = raw_remote in ("true", "1", "yes", "t")

    return (title, company, location, description, skills, salary, remote)


def load_jobs_from_csv(csv_path: str, batch_size: int = 100) -> int:
    """Read CSV, clean rows, and batch insert into PostgreSQL jobs table."""
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"CSV dataset not found at: {csv_path}")

    # Ensure schema and pgvector extension are created
    logger.info("Verifying database schema...")
    init_db()

    cleaned_rows: List[Tuple[Any, ...]] = []
    with open(csv_path, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            cleaned = clean_job_row(row)
            # Skip invalid rows missing mandatory title or description
            if cleaned[0] and cleaned[3]:
                cleaned_rows.append(cleaned)

    total_records = len(cleaned_rows)
    logger.info(f"Read and cleaned {total_records} valid job records from {csv_path}")

    insert_sql = """
        INSERT INTO jobs (title, company, location, description, skills, salary, remote)
        VALUES %s;
    """

    inserted = 0
    with get_db_connection() as conn:
        with conn.cursor() as cur:
            for i in range(0, total_records, batch_size):
                batch = cleaned_rows[i : i + batch_size]
                execute_values(cur, insert_sql, batch)
                conn.commit()
                inserted += len(batch)
                logger.info(f"Inserted {inserted}/{total_records} jobs...")

    logger.info(f"Successfully loaded {inserted} jobs into the database.")
    return inserted


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Load cleaned job postings into Postgres.")
    parser.add_argument(
        "--file",
        type=str,
        default=os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "jobs.csv"),
        help="Path to jobs CSV dataset",
    )
    parser.add_argument(
        "--embed",
        action="store_true",
        help="Automatically generate and save embeddings after loading",
    )
    args = parser.parse_args()

    try:
        loaded_count = load_jobs_from_csv(args.file)
        if args.embed:
            from scripts.generate_embeddings import generate_and_store_embeddings
            generate_and_store_embeddings()
    except psycopg2.OperationalError as e:
        logger.error(
            "\n[Database Connection Error]: Could not connect to PostgreSQL.\n"
            "Please ensure DATABASE_URL is set in your .env file or environment.\n"
            "Example for Neon:\n"
            "DATABASE_URL=postgresql://user:password@ep-xyz.us-east-2.aws.neon.tech/neondb?sslmode=require\n"
            f"Details: {e}"
        )
        sys.exit(1)
